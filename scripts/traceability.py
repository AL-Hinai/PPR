"""Build docs/validation/traceability.md: each URS requirement and the automated tests that verify it.

    python scripts/traceability.py          # from test markers only
    python scripts/traceability.py --run    # also run the tests and record pass/fail per test

Tests declare what they verify with ``@pytest.mark.req("URS-nn")`` (or a module-level ``pytestmark``).
Requirements come from the table in docs/validation/urs.md. Exit code 1 if a requirement has no test or a
marked test failed.
"""
import argparse
import datetime
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
URS = ROOT / "docs" / "validation" / "urs.md"
OUT = ROOT / "docs" / "validation" / "traceability.md"


class Collector:
    def __init__(self):
        self.tests = defaultdict(list)  # requirement -> node ids
        self.outcomes = {}

    def pytest_collection_modifyitems(self, items):
        for item in items:
            for mark in item.iter_markers("req"):
                self.tests[mark.args[0]].append(item.nodeid)

    def pytest_runtest_logreport(self, report):
        if report.when == "call" or (report.when == "setup" and report.outcome != "passed"):
            self.outcomes[report.nodeid] = report.outcome


def requirements() -> list[tuple[str, str]]:
    rows = re.findall(r"^\| (URS-\d+) \| (.+?) \|", URS.read_text(encoding="utf-8"), re.MULTILINE)
    return [(rid, text) for rid, text in rows]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run", action="store_true", help="run the tests and record their results")
    args = parser.parse_args()

    collector = Collector()
    pytest_args = ["-q", "-p", "no:cacheprovider", str(ROOT / "tests")]
    if not args.run:
        pytest_args.insert(0, "--collect-only")
    pytest.main(pytest_args, plugins=[collector])

    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    lines = [
        "# Traceability matrix",
        "",
        f"Generated by `scripts/traceability.py{' --run' if args.run else ''}` on "
        f"{datetime.date.today():%d %B %Y} (commit `{commit or 'n/a'}`, uncommitted changes not shown). "
        "Do not edit by hand.",
        "",
        "| Requirement | Tests | Result |",
        "|---|---|---|",
    ]
    problems = 0
    for rid, text in requirements():
        tests = sorted(set(collector.tests.get(rid, [])))
        if not tests:
            result, problems = "**No test**", problems + 1
        elif args.run:
            failed = [t for t in tests if collector.outcomes.get(t) not in ("passed",)]
            result = f"**{len(failed)} failed**" if failed else f"{len(tests)} passed"
            problems += bool(failed)
        else:
            result = f"{len(tests)} tests"
        names = "<br>".join(f"`{t.split('::', 1)[0].removeprefix('tests/')}::{t.split('::', 1)[1]}`" for t in tests[:12])
        if len(tests) > 12:
            names += f"<br>… and {len(tests) - 12} more"
        lines.append(f"| **{rid}** {text} | {names or '—'} | {result} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(requirements())} requirements, {problems} problem(s).")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    sys.exit(main())
