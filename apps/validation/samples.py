# --- XML backbone ----------------------------------------------------------------

def _leaf(parent, number, doc, files, href):
    leaf = etree.SubElement(parent, "leaf")
    leaf.set("ID", leaf_id(number, doc.path))
    leaf.set("operation", doc.operation)
    if doc.modified_file:
        leaf.set("modified-file", doc.modified_file)
    leaf.set("checksum-type", "md5")
    leaf.set("checksum", md5(files[doc.path]) if doc.operation != "delete" else "")
    leaf.set(f"{{{XLINK_NS}}}type", "simple")
    if doc.operation != "delete":
        leaf.set(f"{{{XLINK_NS}}}href", href)
    etree.SubElement(leaf, "title").text = doc.title
    return leaf


def _section(parent, segment):
    tag, attrs = (segment, {}) if isinstance(segment, str) else segment
    for child in parent:
        if child.tag == tag and dict(child.attrib) == attrs:
            return child
    element = etree.SubElement(parent, tag)
    for key, value in attrs.items():
        element.set(key, value)
    return element


def regional_xml(number, docs, files, region, application_title) -> bytes:
    ns = f"urn:ppr:ectd:{region}-regional"
    root = etree.Element(f"{{{ns}}}{region}-regional", nsmap={region: ns, "xlink": XLINK_NS})
    admin = etree.SubElement(root, "admin")
    etree.SubElement(admin, "applicant").text = PRODUCT["manufacturer"]
    etree.SubElement(admin, "product-name").text = application_title
    etree.SubElement(admin, "sequence").text = number
    body = etree.SubElement(root, f"m1-{region}")
    for doc in docs:
        section = _section(body, doc.regional_section)
        _leaf(section, number, doc, files, doc.path.split("/", 2)[2])
    return etree.tostring(root, xml_declaration=True, encoding="UTF-8", pretty_print=True)


def index_xml(number, docs, files, regional_rel) -> bytes:
    root = etree.Element(f"{{{ECTD_NS}}}ectd", nsmap={"ectd": ECTD_NS, "xlink": XLINK_NS})
    root.set("dtd-version", "3.2")
    m1 = etree.SubElement(root, MODULES["m1"])
    regional_doc = Doc(regional_rel, "Regional administrative information")
    _leaf(m1, number, regional_doc, files, regional_rel)
    for doc in docs:
        parent = root
        for segment in doc.section:
            parent = _section(parent, segment)
        _leaf(parent, number, doc, files, doc.path)
    return etree.tostring(
        root,
        xml_declaration=True,
        encoding="UTF-8",
        pretty_print=True,
        doctype='<!DOCTYPE ectd:ectd SYSTEM "util/dtd/ich-ectd-3-2.dtd">',
    )


def build_files(
    number: str = "0000",
    documents: list[Doc] | None = None,
    application_type: str = "NEW_DRUG",
    region: str | None = None,
    product_title: str = PRODUCT["product-name"],
) -> dict[str, bytes]:
    """All files of one sequence, keyed by path relative to the sequence folder."""
    region = region or settings.ECTD_REGION
    docs = documents if documents is not None else initial_documents(application_type, region)
    files: dict[str, bytes] = {}
    for doc in docs:
        if doc.operation != "delete":
            files[doc.path] = doc.content if doc.content is not None else make_pdf(f"{doc.title} - {product_title}")

    regional_rel = f"m1/{region}/{region}-regional.xml"
    files[regional_rel] = regional_xml(number, [d for d in docs if d.regional_section], files, region, product_title)
    files["index.xml"] = index_xml(number, [d for d in docs if not d.regional_section], files, regional_rel)
    files["index-md5.txt"] = md5(files["index.xml"]).encode()
    files["util/dtd/ich-ectd-3-2.dtd"] = Path(settings.ECTD_DTD_PATH).read_bytes()
    return files


def refresh_index_md5(files: dict[str, bytes]) -> None:
    files["index-md5.txt"] = md5(files["index.xml"]).encode()


def to_zip(files: dict[str, bytes], number: str = "0000", extra: dict[str, bytes] | None = None) -> bytes:
    """Zip the sequence as ``<number>/...``; ``extra`` entries are added with their raw names."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, data in sorted(files.items()):
            archive.writestr(f"{number}/{path}", data)
        for name, data in (extra or {}).items():
            archive.writestr(name, data)
    return buffer.getvalue()


def build_package(number="0000", application_type="NEW_DRUG", documents=None, **kwargs) -> bytes:
    return to_zip(build_files(number, documents, application_type, **kwargs), number)
