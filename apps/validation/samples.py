@dataclass
class Doc:
    path: str  # relative to the sequence folder
    title: str
    section: tuple = ()  # element path in index.xml; empty for regional (Module 1) documents
    regional_section: str = ""  # element in the regional XML
    operation: str = "new"
    modified_file: str = ""
    content: bytes | None = None
    attrs: dict = field(default_factory=dict)


def leaf_id(number: str, path: str) -> str:
    return "leaf-" + hashlib.sha1(f"{number}/{path}".encode()).hexdigest()[:12]


def md5(data: bytes) -> str:
    return hashlib.md5(data).hexdigest()


# --- minimal, standards-conformant PDF ---------------------------------------

def _pdf_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def make_pdf(text: str, version: str = "1.7", javascript: bool = False, font: str = "Helvetica") -> bytes:
    """A one-page PDF. The default font is one of the 14 standard PDF fonts (no embedding needed)."""
    lines = [text[i : i + 80] for i in range(0, len(text), 80)] or [""]
    ops = ["BT", "/F1 16 Tf", "72 770 Td", f"({_pdf_escape(lines[0])}) Tj", "/F1 11 Tf"]
    for line in lines[1:]:
        ops += ["0 -18 Td", f"({_pdf_escape(line)}) Tj"]
    ops += ["0 -30 Td", "(Sample document generated by PPR for demonstration purposes.) Tj", "ET"]
    stream = "\n".join(ops).encode("latin-1", "replace")

    catalog = b"<< /Type /Catalog /Pages 2 0 R" + (b" /OpenAction 6 0 R" if javascript else b"") + b" >>"
    objects = [
        catalog,
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        f"<< /Type /Font /Subtype /TrueType /BaseFont /{font} >>".encode() if font != "Helvetica"
        else b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
    ]
    if javascript:
        objects.append(b"<< /S /JavaScript /JS (app.alert\\('hello'\\);) >>")

    out = io.BytesIO()
    out.write(f"%PDF-{version}\n".encode() + b"%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{number} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode())
    for offset in offsets:
        out.write(f"{offset:010d} 00000 n \n".encode())
    out.write(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return out.getvalue()


